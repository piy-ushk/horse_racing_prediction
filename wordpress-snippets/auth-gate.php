<?php
/**
 * LINE Auth Gate for Horse Racing Prediction Pages
 *
 * HOW TO INSTALL (choose one):
 *   A) Add to your theme's functions.php
 *   B) Create as a must-use plugin: wp-content/mu-plugins/keiba-auth-gate.php
 *
 * WHAT IT DOES:
 *   - Race prediction pages (slug starts with "race-") require ?auth=line_only
 *   - Missing or wrong parameter → redirect to home page
 *   - All race pages get noindex / nofollow to block search engine indexing
 */

if ( ! defined( 'ABSPATH' ) ) {
    exit;
}

/**
 * Server-side access gate: redirect to home if the auth parameter is missing.
 * This runs before WordPress renders the page, so there is no flash of content.
 */
function keiba_line_auth_gate() {
    if ( ! is_page() ) {
        return;
    }

    $post = get_post();
    if ( ! $post || strpos( $post->post_name, 'race-' ) !== 0 ) {
        return;
    }

    $auth = isset( $_GET['auth'] ) ? sanitize_key( $_GET['auth'] ) : '';
    if ( $auth !== 'line_only' ) {
        wp_redirect( home_url( '/' ), 302 );
        exit;
    }
}
add_action( 'template_redirect', 'keiba_line_auth_gate' );


/**
 * Force noindex + nofollow on all race prediction pages.
 * Compatible with WordPress 5.7+ robots API (works alongside Yoast SEO).
 */
function keiba_noindex_race_pages( array $robots ): array {
    if ( is_page() ) {
        $post = get_post();
        if ( $post && strpos( $post->post_name, 'race-' ) === 0 ) {
            $robots['noindex']  = true;
            $robots['nofollow'] = true;
        }
    }
    return $robots;
}
add_filter( 'wp_robots', 'keiba_noindex_race_pages' );


/**
 * Exclude race prediction pages from XML sitemaps generated by WordPress core.
 * (Yoast SEO has its own sitemap filter — set noindex via the Yoast meta box too.)
 */
function keiba_exclude_from_sitemap( bool $excluded, \WP_Post $post ): bool {
    if ( strpos( $post->post_name, 'race-' ) === 0 ) {
        return true;
    }
    return $excluded;
}
add_filter( 'wp_sitemaps_posts_entry', function( $entry, $post ) {
    if ( $post instanceof \WP_Post && strpos( $post->post_name, 'race-' ) === 0 ) {
        return false;
    }
    return $entry;
}, 10, 2 );
